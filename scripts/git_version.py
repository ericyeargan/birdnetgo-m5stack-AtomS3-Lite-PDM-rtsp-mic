"""PlatformIO pre-build script: write the current git hash to include/GitVersion.h.

The header is only rewritten when its contents change, so a new commit
recompiles just the file that includes it instead of the whole project.
"""

from pathlib import Path
import subprocess

Import("env")  # noqa: F821 - provided by PlatformIO/SCons

ROOT = Path(env["PROJECT_DIR"])  # noqa: F821
OUT = ROOT / "include" / "GitVersion.h"


def git(*args: str) -> str:
    return subprocess.run(
        ["git", *args], cwd=ROOT, capture_output=True, text=True, check=True
    ).stdout.strip()


try:
    rev = git("rev-parse", "--short=7", "HEAD")
    if git("status", "--porcelain", "--untracked-files=no"):
        rev += "-dirty"
except (OSError, subprocess.CalledProcessError):
    rev = "unknown"

content = (
    "// Generated by scripts/git_version.py - do not edit.\n"
    "#pragma once\n"
    f'#define FW_GIT_REV "{rev}"\n'
)

if not OUT.is_file() or OUT.read_text(encoding="utf-8") != content:
    OUT.write_text(content, encoding="utf-8")

print(f"Firmware git revision: {rev}")
